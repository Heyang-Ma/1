#include <iostream>
#include <SFML/Graphics.hpp>
#include "Game.h"

using namespace std;

int main() {
    cout << "============================================" << endl;
    cout << "  简易战旗游戏 - FSM vs 行为树 AI 比较" << endl;
    cout << "============================================" << endl;
    cout << endl;

    // 创建窗口
    // 窗口大小：8格×64像素 = 512 像素宽，加上右侧信息栏
    sf::RenderWindow window(sf::VideoMode({800, 600}), "Tactical Game - FSM vs Behavior Tree");
    window.setVerticalSyncEnabled(true);
    window.setFramerateLimit(60);

    // 创建并初始化游戏
    Game game;
    game.init();

    // 时钟用于计算帧时间
    sf::Clock clock;

    cout << "\n游戏启动成功！" << endl;
    cout << "按 Tab 键在 FSM 和 行为树 之间切换AI" << endl;
    cout << "观察控制台输出以了解AI决策过程\n" << endl;

    // 主游戏循环
    while (window.isOpen()) {
        // 计算帧时间
        sf::Time elapsed = clock.restart();
        float dt = elapsed.asSeconds();

        // 处理事件
        game.handleEvents(window);

        // 更新游戏状态
        game.update(dt);

        // 渲染
        window.clear(sf::Color(40, 40, 60));  // 深蓝灰色背景
        game.render(window);
        window.display();
    }

    cout << "\n游戏结束，感谢游玩！" << endl;

    return 0;
}
